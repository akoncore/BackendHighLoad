-- Product Catalog (T5) - PostgreSQL schema
-- Target: PostgreSQL 14+ (gen_random_uuid() is built in since 13).
-- Source of truth for all catalog data. Redis, L1, Elasticsearch and CDN are derived copies.

BEGIN;

-- ---------------------------------------------------------------------------
-- Reference tables
-- ---------------------------------------------------------------------------

CREATE TABLE categories (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(100) NOT NULL,
    parent_id  integer REFERENCES categories (id)   -- NULL = root category
);

CREATE INDEX idx_categories_parent ON categories (parent_id);

CREATE TABLE brands (
    id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  varchar(100) NOT NULL UNIQUE
);

-- ---------------------------------------------------------------------------
-- Products (~2 KB per row, ~2 GB for 1M rows, see docs/04-capacity-estimation.md)
-- ---------------------------------------------------------------------------

CREATE TABLE products (
    id           uuid          PRIMARY KEY DEFAULT gen_random_uuid(),
    title        varchar(200)  NOT NULL,
    description  text,
    price        numeric(12,2) NOT NULL CHECK (price >= 0),   -- never float for money
    currency     char(3)       NOT NULL,                      -- ISO 4217, e.g. KZT
    brand_id     integer       REFERENCES brands (id),
    category_id  integer       NOT NULL REFERENCES categories (id),
    attributes   jsonb         NOT NULL DEFAULT '{}'::jsonb,  -- heterogeneous specs (ram, color, size...)
    image_urls   text[]        NOT NULL DEFAULT '{}',         -- CDN URLs only; files live in S3
    stock        integer       NOT NULL DEFAULT 0 CHECK (stock >= 0),
    version      integer       NOT NULL DEFAULT 1,            -- optimistic lock, ES external version
    updated_at   timestamptz   NOT NULL DEFAULT now()
);

-- Category listing: equality on category_id, then sorted by price; id makes the cursor unique.
-- INCLUDE (title) lets the list page be answered by an Index Only Scan.
CREATE INDEX idx_products_cat_price
    ON products (category_id, price, id) INCLUDE (title);

-- Attribute lookups: attributes @> '{"storage": "128GB"}'
CREATE INDEX idx_products_attrs
    ON products USING GIN (attributes jsonb_path_ops);

-- Supports the brand foreign key and brand-only lookups.
CREATE INDEX idx_products_brand ON products (brand_id);

-- ---------------------------------------------------------------------------
-- Transactional outbox (written in the SAME transaction as the product change).
-- Debezium (CDC) reads this table and publishes to Kafka topic `product-changes`.
-- Clean up published rows periodically (e.g. delete rows older than 7 days).
-- ---------------------------------------------------------------------------

CREATE TABLE outbox (
    id            bigint      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    aggregate_id  uuid        NOT NULL,                       -- product id, used as Kafka key
    type          text        NOT NULL
                  CHECK (type IN ('product_created', 'product_updated', 'product_deleted')),
    payload       jsonb       NOT NULL,                       -- includes id and version
    created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_outbox_created ON outbox (created_at);

-- ---------------------------------------------------------------------------
-- Idempotency keys for POST /products (client-generated UUID per logical operation).
-- The PRIMARY KEY is the unique constraint that makes concurrent retries safe.
-- Delete rows older than 24 hours.
-- ---------------------------------------------------------------------------

CREATE TABLE idempotency_keys (
    key           uuid        PRIMARY KEY,
    request_hash  text        NOT NULL,                       -- detects same key + different body
    status_code   smallint,                                   -- NULL while the first request is in progress
    response      jsonb,                                      -- stored response, replayed on retry
    created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_idempotency_created ON idempotency_keys (created_at);

COMMIT;

